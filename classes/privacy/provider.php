namespace local_transcript\privacy;

use core_privacy\local\metadata\collection;
use core_privacy\local\request\approved_contextlist;
use core_privacy\local\request\approved_userlist;
use core_privacy\local\request\contextlist;
use core_privacy\local\request\transform;
use core_privacy\local\request\userlist;
use core_privacy\local\request\writer;

/**
 * Privacy API implementation for the Student Transcript plugin.
 *
 * Transcripts are stored in the system context. A transcript is about a student and was generated by a user
 * (often the same person). Both are covered.
 *
 * @package    local_transcript
 * @copyright  2026 Roy Jensen (created and copyrighted by Roy Jensen; development by Claude AI, Anthropic)
 * @copyright  The layout designer is modelled on mod_customcert (Custom Certificate), copyright 2013 Mark Nelson
 *             <markn@moodle.com> and contributors, https://moodle.org/plugins/mod_customcert (GNU GPL v3 or later)
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class provider implements
    \core_privacy\local\metadata\provider,
    \core_privacy\local\request\plugin\provider,
    \core_privacy\local\request\userlist_provider {

    /**
     * Describe the data that is stored.
     *
     * @param collection $collection
     * @return collection
     */
    public static function get_metadata(collection $collection): collection {
        $collection->add_database_table('local_transcript_issue', [
            'userid' => 'privacy:metadata:issue:userid',
            'issuedby' => 'privacy:metadata:issue:issuedby',
            'templatename' => 'privacy:metadata:issue:templatename',
            'code' => 'privacy:metadata:issue:code',
            'snapshot' => 'privacy:metadata:issue:snapshot',
            'timecreated' => 'privacy:metadata:issue:timecreated',
        ], 'privacy:metadata:issue');

        $collection->add_external_location_link('emailrecipient', [
            'emailaddress' => 'privacy:metadata:email:emailaddress',
            'transcript' => 'privacy:metadata:email:transcript',
        ], 'privacy:metadata:email');
        return $collection;
    }

    /**
     * The contexts that hold data of a user.
     *
     * @param int $userid
     * @return contextlist
     */
    public static function get_contexts_for_userid(int $userid): contextlist {
        $contextlist = new contextlist();
        $sql = "SELECT ctx.id
                  FROM {context} ctx
                 WHERE ctx.contextlevel = :level
                   AND EXISTS (SELECT 1 FROM {local_transcript_issue} i WHERE i.userid = :userid OR i.issuedby = :issuedby)";
        $contextlist->add_from_sql($sql, ['level' => CONTEXT_SYSTEM, 'userid' => $userid, 'issuedby' => $userid]);
        return $contextlist;
    }

    /**
     * The users with data in a context.
     *
     * @param userlist $userlist
     */
    public static function get_users_in_context(userlist $userlist): void {
        if (!$userlist->get_context() instanceof \context_system) {
            return;
        }
        $userlist->add_from_sql('userid', 'SELECT userid FROM {local_transcript_issue}', []);
        $userlist->add_from_sql('issuedby', 'SELECT issuedby FROM {local_transcript_issue} WHERE issuedby > 0', []);
    }

    /**
     * Export the transcripts of a user: the ones about the user and the ones the user generated.
     *
     * @param approved_contextlist $contextlist
     */
    public static function export_user_data(approved_contextlist $contextlist): void {
        global $DB;

        $userid = $contextlist->get_user()->id;
        $systemcontext = \context_system::instance();
        if (!in_array($systemcontext->id, $contextlist->get_contextids())) {
            return;
        }

        $records = $DB->get_records_select('local_transcript_issue', 'userid = :userid OR issuedby = :issuedby',
            ['userid' => $userid, 'issuedby' => $userid], 'timecreated ASC');
        $transcripts = [];
        foreach ($records as $record) {
            $model = json_decode($record->snapshot, true) ?: [];
            $courses = [];
            foreach (($model['courses'] ?? []) as $course) {
                $courses[] = [
                    'course' => $course['fullname'] ?? '',
                    'code' => $course['shortname'] ?? '',
                    'status' => $course['status'] ?? '',
                    'grade' => $course['grade'] ?? '',
                    'completiondate' => !empty($course['completiondate']) ? transform::datetime($course['completiondate']) : '',
                ];
            }
            $transcripts[] = [
                'layout' => $record->templatename,
                'verificationcode' => $record->code,
                'generatedon' => transform::datetime($record->timecreated),
                'aboutthisuser' => transform::yesno((int) $record->userid === (int) $userid),
                'generatedbythisuser' => transform::yesno((int) $record->issuedby === (int) $userid),
                'student' => $model['user']['fullname'] ?? '',
                'courses' => $courses,
            ];
        }
        if ($transcripts) {
            writer::with_context($systemcontext)->export_data(
                [get_string('pluginname', 'local_transcript')], (object) ['transcripts' => $transcripts]);
        }
    }

    /**
     * Delete the data of everybody in a context.
     *
     * @param \context $context
     */
    public static function delete_data_for_all_users_in_context(\context $context): void {
        global $DB;
        if (!$context instanceof \context_system) {
            return;
        }
        $fs = get_file_storage();
        foreach ($DB->get_fieldset_select('local_transcript_issue', 'id', '1 = 1') as $issueid) {
            $fs->delete_area_files($context->id, 'local_transcript', \local_transcript\template::FILEAREA_ISSUE, $issueid);
        }
        $DB->delete_records('local_transcript_issue');
    }

    /**
     * Delete the data of one user. Transcripts about the user are deleted. For the transcripts that the user
     * generated about somebody else, only the name of the user is removed.
     *
     * @param approved_contextlist $contextlist
     */
    public static function delete_data_for_user(approved_contextlist $contextlist): void {
        $systemcontext = \context_system::instance();
        if (!in_array($systemcontext->id, $contextlist->get_contextids())) {
            return;
        }
        self::delete_for_userids([$contextlist->get_user()->id]);
    }

    /**
     * Delete the data of several users in a context.
     *
     * @param approved_userlist $userlist
     */
    public static function delete_data_for_users(approved_userlist $userlist): void {
        if (!$userlist->get_context() instanceof \context_system) {
            return;
        }
        self::delete_for_userids($userlist->get_userids());
    }

    /**
     * Delete the transcripts about users and remove the users as the person who generated a transcript.
     *
     * @param int[] $userids
     */
    private static function delete_for_userids(array $userids): void {
        global $DB;
        if (!$userids) {
            return;
        }
        $context = \context_system::instance();
        $fs = get_file_storage();

        [$insql, $inparams] = $DB->get_in_or_equal($userids, SQL_PARAMS_NAMED);
        foreach ($DB->get_fieldset_select('local_transcript_issue', 'id', "userid $insql", $inparams) as $issueid) {
            $fs->delete_area_files($context->id, 'local_transcript', \local_transcript\template::FILEAREA_ISSUE, $issueid);
        }
        $DB->delete_records_select('local_transcript_issue', "userid $insql", $inparams);

        [$insql, $inparams] = $DB->get_in_or_equal($userids, SQL_PARAMS_NAMED);
        $DB->set_field_select('local_transcript_issue', 'issuedby', 0, "issuedby $insql", $inparams);
    }
}
